pub fn assert_ascending(arr: &[f32]) {
    for i in 1..arr.len() {
        assert!(
            arr[i] >= arr[i - 1],
            "Array is not in ascending order at index {}: {} < {}",
            i,
            arr[i],
            arr[i - 1]
        );
    }
}
